"""Constellation ONTS benchmark on the factorial design of Antunes et al. (2026).

36 instances: T in {96,144,192}, S in {5,10,15}, Js in {8,12}, Jc in {4,8},
generated by their Algorithm 3 (with bundled orbit solar profiles and exact
per-task acceptance). Instances differ from the paper's (no published seeds or
solar data), so objective values are not comparable with its tables.
"""

from __future__ import annotations

import argparse
import itertools
import json
import os
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

from projects.scheduling.constellation import (
    generate_constellation,
    solve_constellation,
    validate_constellation,
)

ROOT = Path(__file__).resolve().parents[1]
DESIGN = list(itertools.product((96, 144, 192), (5, 10, 15), (8, 12), (4, 8)))
BASE = 71_000_000


def run(task):
    index, method, budget, seed = task
    os.environ["ONTS_SOLVER_THREADS"] = "1"
    T, S, Js, Jc = DESIGN[index]
    inst = generate_constellation(S=S, Js=Js, Jc=Jc, T=T, seed=BASE + index)
    result = solve_constellation(
        inst,
        time_limit=budget,
        mode="exact" if method == "exact" else "portfolio",
        seed=seed,
    )
    X = result["schedule"]
    objective = None
    if X is not None:
        objective, bad = validate_constellation(inst, X)
        if bad:
            raise RuntimeError(f"invalid schedule {index} {method}: {bad[:3]}")
    history = [(float(t), float(v)) for t, v in result["history"]]
    credited = objective if history and history[-1][0] <= budget + 0.5 else None
    return dict(
        index=index,
        T=T,
        S=S,
        Js=Js,
        Jc=Jc,
        method=method,
        seed=seed,
        objective=credited,
        returned_objective=objective,
        first=history[0][0] if history else None,
        status=result.get("status"),
        bound=result.get("bound"),
        runtime=result["runtime"],
        iterations=result.get("iterations"),
        repairs=result.get("repairs"),
        redraws=inst.redraws,
        history=history,
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=ROOT / "research/results/constellation"
    )
    parser.add_argument("--budget", type=float, default=60.0)
    parser.add_argument("--workers", type=int, default=8)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    tasks = [
        (i, m, args.budget, args.seed)
        for i in range(len(DESIGN))
        for m in ("portfolio", "exact")
    ]
    with ProcessPoolExecutor(args.workers) as pool:
        rows = list(pool.map(run, tasks))
    (args.output / "runs.json").write_text(json.dumps(rows, indent=1) + "\n")
    by = {}
    for r in rows:
        by.setdefault(r["index"], {})[r["method"]] = r
    lines = [
        "| # | T | S | Js | Jc | portfolio | first (s) | exact | status | bound | gap to bound |",
        "|---|---|---|---|---|---:|---:|---:|---|---:|---:|",
    ]
    for i, m in sorted(by.items()):
        p, e = m["portfolio"], m["exact"]
        gap = (
            f"{100 * (e['bound'] - p['objective']) / e['bound']:.2f}%"
            if e["bound"] and p["objective"]
            else "—"
        )
        fmt = lambda v: f"{v:.0f}" if v is not None else "—"  # noqa: E731
        lines.append(
            f"| {i + 1} | {p['T']} | {p['S']} | {p['Js']} | {p['Jc']} | "
            f"{fmt(p['objective'])} | {p['first'] or float('nan'):.1f} | "
            f"{fmt(e['objective'])} | {e['status']} | {fmt(e['bound'])} | {gap} |"
        )
    feas = {
        k: sum(m[k]["objective"] is not None for m in by.values())
        for k in ("portfolio", "exact")
    }
    both = [
        m
        for m in by.values()
        if m["exact"]["objective"] and m["portfolio"]["objective"]
    ]
    ratio = [m["portfolio"]["objective"] / m["exact"]["objective"] for m in both]
    lines += [
        "",
        f"Feasible by deadline: portfolio {feas['portfolio']}/36, exact {feas['exact']}/36.",
        f"Where both feasible ({len(both)}): portfolio/exact objective ratio mean "
        f"{np.mean(ratio) if ratio else float('nan'):.4f}, "
        f"min {min(ratio) if ratio else float('nan'):.4f}.",
    ]
    (args.output / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[-3:]))


if __name__ == "__main__":
    main()
